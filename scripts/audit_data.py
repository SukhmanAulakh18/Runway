"""Data audit: checks the Tangerine data and records every quirk and what we do about it.

    python scripts/audit_data.py            # prints the report and writes docs/DATA_AUDIT.md

The data needs no row-level cleaning (no missing values in the files the app uses). "Cleaning" here means
checking integrity and deciding how to treat each quirk; those decisions live in engine.py and are listed below.
"""
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(os.environ.get("RUNWAY_DATA", ROOT / "data"))
lines = []


def out(s=""):
    print(s)
    lines.append(s)


def main():
    m = pd.read_csv(DATA / "monthly_summary.csv")
    L = pd.read_csv(DATA / "loans.csv", parse_dates=["loan_start"])
    acc = pd.read_csv(DATA / "accounts.csv")
    cl = pd.read_csv(DATA / "clients.csv", parse_dates=["birth_date"])
    dp = pd.read_csv(DATA / "dispositions.csv")
    di = pd.read_csv(DATA / "districts.csv")
    so = pd.read_csv(DATA / "standing_orders.csv")
    checks = []

    def chk(name, ok, detail):
        checks.append((name, "pass" if ok else "FAIL", detail))

    out("# Data audit")
    out("")
    out("Generated by `python scripts/audit_data.py` from the Tangerine CSVs. Rerun it any time.")
    out("")
    out("## 1. Files")
    out("")
    out("| File | Rows | Columns | Missing values |")
    out("|---|---|---|---|")
    for name, df in [("monthly_summary", m), ("loans", L), ("accounts", acc), ("clients", cl), ("dispositions", dp),
                     ("standing_orders", so), ("districts", di)]:
        miss = int(df.isna().sum().sum())
        out(f"| {name}.csv | {len(df):,} | {df.shape[1]} | {miss:,} |")
    out("")
    out(f"Months covered: {m.month.min()} to {m.month.max()}. Accounts: {m.account_id.nunique():,}; "
        f"months per account: {m.groupby('account_id').size().min()} to {m.groupby('account_id').size().max()} "
        f"(median {int(m.groupby('account_id').size().median())}).")

    # integrity checks
    inn = ["cash_deposits", "transfers_in", "pension_in", "interest_in"]
    outc = ["household_bills", "insurance", "loan_payments", "bank_fees", "cash_withdrawals_genuine", "card_withdrawals", "transfers_out_other"]
    chk("money_in parts add up", (m[inn].sum(axis=1) - m.money_in).abs().max() < 1e-6, "cash + transfers + pension + interest = money_in")
    chk("money_out parts add up", (m[outc].sum(axis=1) - m.money_out).abs().max() < 1e-6, "7 components = money_out")
    chk("one row per account-month", not m.duplicated(["account_id", "month"]).any(), "no duplicate (account_id, month)")
    chk("no negative flows", (m[["money_in", "money_out"]] >= 0).all().all(), "money_in, money_out ≥ 0")
    chk("every account has monthly data", set(acc.account_id) == set(m.account_id), "accounts.csv ↔ monthly_summary.csv")
    chk("every loan's account exists", set(L.account_id) <= set(acc.account_id), "loans.csv → accounts.csv")
    chk("one loan per account", not L.account_id.duplicated().any(), "loans.csv")
    chk("loan amount = months × payment", (L.amount - L.duration_months * L.monthly_payment).abs().max() < 1e-6, "loans.csv")
    end = [s + pd.DateOffset(months=int(n)) for s, n in zip(L.loan_start, L.duration_months)]
    running = pd.Series(end) > pd.Timestamp("2025-12-31")
    chk("running at end-2025 = status C/D", set(L.status[running.values]) == {"C", "D"} and set(L.status[~running.values]) == {"A", "B"},
        "so 'loan payment P' can use the date rule")
    chk("dispositions link people to accounts", set(dp.client_id) == set(cl.client_id) and set(dp.account_id) <= set(acc.account_id), "")
    out("")
    out("## 2. Integrity checks")
    out("")
    out("| Check | Result | Detail |")
    out("|---|---|---|")
    for n_, r_, d_ in checks:
        out(f"| {n_} | {r_} | {d_} |")

    # quirks and decisions
    g = m.groupby("account_id")
    cash_share = m.cash_deposits.sum() / m.money_in.sum()
    atm_share = m.cash_withdrawals_genuine.sum() / m.money_out.sum()
    H0 = int((g.household_bills.median() == 0).sum())
    B = m.sort_values("month").groupby("account_id").tail(6).groupby("account_id").avg_daily_balance.mean()
    stale = int((g.month.max() < "2025-12").sum())
    own = dp[dp.type == "owner"].merge(cl, on="client_id").set_index("account_id")
    age = (pd.Timestamp("2025-12-31") - own.birth_date).dt.days / 365.25
    pen = int((g.pension_in.sum() > 0).sum())
    ms = m.sort_values(["account_id", "month"]).copy()
    ms["k"] = ms.groupby("account_id").cumcount()
    opening = ms[ms.k == 0].set_index("account_id").min_balance
    next5 = ms[(ms.k >= 1) & (ms.k <= 5)].groupby("account_id").avg_daily_balance.mean()
    first_ratio = float((opening / next5).replace([np.inf, -np.inf], np.nan).median())
    w6 = ms[ms.groupby("account_id").k.transform("max") >= 11].groupby("account_id").tail(6).groupby("account_id")
    later_ratio = float((w6.min_balance.min() / w6.avg_daily_balance.mean()).median())
    corr = di[["unemployment_rate_2022", "unemployment_rate_2023"]].corr().iloc[0, 1]
    blank = None
    tx = DATA / "transactions.csv"
    if tx.exists():
        t = pd.read_csv(tx, usecols=["purpose"])
        blank = float(t.purpose.isna().mean())
    out("")
    out("## 3. Quirks, and what we do about each")
    out("")
    out("| Quirk | Evidence | Our decision (in engine.py) |")
    out("|---|---|---|")
    out(f"| Origin | PKDD'99 Czech bank data, re-dated to 2020–2025, money relabelled CAD | Say so openly; use Canadian sources only to size shocks (EI cap) |")
    out(f"| Cash economy | {cash_share:.0%} of money in is cash deposits; {atm_share:.0%} of money out is cash withdrawals | Say 'money in / money out', not income/spending; EI share is an explicit slider |")
    if blank is not None:
        out(f"| Thin labels | {blank:.0%} of transactions have no purpose | Call unlabelled outflows 'purpose unknown'; never assume they're discretionary |")
    out(f"| No labelled bills | {H0:,} accounts have median household bills = 0 | Flag it: a 'bills +X%' shock changes nothing in the standard formula |")
    out(f"| Negative buffer | {int((B <= 0).sum())} accounts have buffer ≤ 0 | Runway 0 before any shock; flagged |")
    out(f"| Stale accounts | {stale} accounts have no activity in the final month(s) | Say 'no activity after YYYY-MM', never 'closed' |")
    out(f"| Opening month | an account's opening balance is a median {first_ratio:.0%} of its next 5 months' average (a normal 6-month trough ratio is {later_ratio:.2f}), so windows that include the opening look like a near-zero dip | Trough score only with 12+ months of history |")
    out(f"| Pensioners | {pen:,} accounts receive pension income | Pension is protected in a layoff (realistic runway); flagged |")
    out(f"| Minors | {int((age < 18).sum())} account owners are under 18 | Flagged: job-loss shocks may not apply |")
    out(f"| District data | 2022 vs 2023 unemployment correlate {corr:.2f}; Czech regions | Not used to size Canadian shocks |")
    out(f"| District 69 | missing 2022 unemployment and crime | Not used by the app |")
    out(f"| Loan outcomes | defaults (B/D) have no default date | We don't predict *when*; we test signals measured before the loan |")
    out("")
    fails = [c for c in checks if c[1] != "pass"]
    out("**Summary:** " + ("all integrity checks pass." if not fails else f"{len(fails)} check(s) failed: " + ", ".join(c[0] for c in fails)))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "DATA_AUDIT.md").write_text("\n".join(lines) + "\n")
    print("\nWrote docs/DATA_AUDIT.md")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
